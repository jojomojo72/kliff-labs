-- Kliff Labs content tables. Run in the Supabase SQL editor, then set
-- SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY in the site's environment.
-- The admin API uses the service role key (server-side only), so RLS can
-- stay enabled with no public policies.

create table if not exists blogs (
  id           bigint generated by default as identity primary key,
  title        text not null,
  description  text not null,
  category     text,
  publisher    text default 'Kliff Labs',
  author       text default 'Kliff Labs Team',
  publish_date date,
  read_time    integer default 3,
  content      text[] default '{}'
);

create table if not exists projects (
  slug     text primary key,
  title    text not null,
  tagline  text not null default '',
  category text not null check (category in ('Web', 'App', 'Web3', 'Branding')),
  year     text not null default '',
  status   text not null default 'live' check (status in ('live', 'in-progress')),
  work     text[] default '{}',
  stack    text[] default '{}',
  link     text,
  featured boolean not null default false
);

alter table blogs enable row level security;
alter table projects enable row level security;

